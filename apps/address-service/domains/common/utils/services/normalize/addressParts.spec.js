const { parser, matchesAddressParts, parseAddressParts } = require('./addressParts')

describe('normalization of address components from real imports', () => {
    test.each([
        ['пгт.Усть-Нера, пер.1-й Октябрьский, д.7/1', 'пгт Усть-Нера, пер Октябрьский 1-й, д 7/1'],
        ['пгт.Усть-Нера, мкр.Нерский, д.55', 'мкр Нерский (пгт Усть-Нера), д 55'],
        ['ул.им. В.А. Маслакова, д.20', 'ул имени В.А. Маслакова, д 20'],
        ['ул.Аренского, д.2/1', 'ул им. Аренского, д 2/1'],
        ['ул.Двенадцатая, соор.22, стр.24', 'ул Двенадцатая, соор 22 стр 24'],
        ['кв-лМеждународный, ул.Загородная, д.2', 'квартал Международный, ул Загородная, д 2'],
        ['5-й мкр., д.28', 'микрорайон 5, д 28'],
        ['п.Цыгановка, ул.Цветочная, д.2', 'сп Цыгановка, ул Цветочная, д 2'],
        ['ул.Пречистенская набережная, д.43', 'наб Пречистенская, д 43'],
        ['рп.Горьковский, ул.Слепцова, д.4', 'тер Рабочий поселок Горьковский, ул им. Слепцова, д 4'],
    ])('matches %s with %s', (source, candidate) => {
        expect(matchesAddressParts(parseAddressParts(source), parseAddressParts(candidate))).toBe(true)
    })

    test.each([
        ['пер.1-й Октябрьский, д.7/1', 'пер Октябрьский 2-й, д 7/1'],
        ['ул.Двенадцатая, соор.22, стр.24', 'ул Двенадцатая, соор 22 стр 23'],
        ['ул.Двенадцатая, соор.22, стр.24', 'ул Двенадцатая, соор 23 стр 24'],
        ['ул.Октябрьская, д 12', 'пер Октябрьский, д 12'],
        ['пгт.Усть-Нера, мкр.Нерский, д 55', 'мкр Нерский (пгт Другой), д 55'],
    ])('distinguishes %s from %s', (source, candidate) => {
        expect(matchesAddressParts(parseAddressParts(source), parseAddressParts(candidate))).toBe(false)
    })

    test.each([
        ['ул.Мира, д.29, нп.подвал, этаж№1, этаж№2, мансарда', 'ул.Мира, д.29', 'подвал, этаж№1, этаж№2, мансарда'],
        ['с.Тополево, кв-л Гринвилль, д.10, № 1', 'с.Тополево, кв-л Гринвилль, д.10', '1'],
        ['ул.Стрелковая, д.18 корпус 2, н/п 3', 'ул.Стрелковая, д.18 корпус 2', '3'],
        ['ул.Гамарника, д.17, нп.-I (1-6, 8-10, 14-20)', 'ул.Гамарника, д.17', '-I (1-6, 8-10, 14-20)'],
        ['г.Колпино, ул.Промышленная, д.3, литер А, нп.1-Н, 2-Н', 'г.Колпино, ул.Промышленная, д.3, литер А', '1-Н, 2-Н'],
    ])('keeps the complete unit of %s', (source, address, unitName) => {
        expect(parser.parseExplicit(source)).toMatchObject({ address, unitName })
    })
})
